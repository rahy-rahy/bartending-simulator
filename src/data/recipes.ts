import type {
  BaseSpirit,
  Difficulty,
  GarnishId,
  GlassType,
  IceType,
  Method,
  Recipe,
  RecipeIngredient,
  RimType,
} from './types'

type Flag = 'top' | 'float' | 'rinse' | 'sink'
type Ing = [id: string, amount: number, flag?: Flag]

interface Opts {
  rim?: RimType
  garnish?: GarnishId[]
  muddle?: boolean
  description: string
  tags?: string[]
  iba?: boolean
  imageQuery?: string
}

function toIngredient([id, amount, flag]: Ing): RecipeIngredient {
  const r: RecipeIngredient = { id, amount }
  if (flag === 'top') {
    r.top = true
    r.note = 'top up'
  } else if (flag === 'float') {
    r.top = true
    r.note = 'float on top'
  } else if (flag === 'sink') {
    r.top = true
    r.note = 'pour last, let it sink'
  } else if (flag === 'rinse') {
    r.note = 'rinse the glass'
  }
  return r
}

function R(
  id: string,
  name: string,
  base: BaseSpirit,
  difficulty: Difficulty,
  glass: GlassType,
  method: Method,
  ice: IceType,
  ingredients: Ing[],
  opts: Opts,
): Recipe {
  return {
    id,
    name,
    base,
    difficulty,
    glass,
    method,
    ice,
    rim: opts.rim ?? 'none',
    garnish: opts.garnish ?? [],
    ingredients: ingredients.map(toIngredient),
    muddle: opts.muddle,
    description: opts.description,
    tags: opts.tags ?? [],
    iba: opts.iba,
    imageQuery: opts.imageQuery,
  }
}

